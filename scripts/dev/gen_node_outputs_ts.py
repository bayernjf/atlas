"""从后端单源投影生成前端节点静态输出根键 TS 产物（打包 AQ／ADR T35，docs/124）。

用法：.venv/bin/python scripts/dev/gen_node_outputs_ts.py
输出：frontend/src/lib/schemas/generated/nodeOutputs.ts

唯一事实源是 ``atlas.graph.node_outputs``（后端 L2 引用复查也从它派生）；
本脚本只是把 ``project_static_outputs()`` 确定性渲染成 TS。生成物提交入仓、
DO NOT EDIT；tests/test_node_output_contract.py 守其逐字节新鲜度——
改了单源必须重跑本脚本，否则后端门红。前端 build/test 不依赖 Python（ADR T35
否决方案 b），故生成物入仓而非构建期现算。
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SRC_ROOT = REPO_ROOT / "src"
if str(SRC_ROOT) not in sys.path:
    sys.path.insert(0, str(SRC_ROOT))

from atlas.graph.node_outputs import project_static_outputs  # noqa: E402

OUT_PATH = REPO_ROOT / "frontend" / "src" / "lib" / "schemas" / "generated" / "nodeOutputs.ts"

GENERATE_COMMAND = ".venv/bin/python scripts/dev/gen_node_outputs_ts.py"


def render() -> str:
    """把单源投影渲染为 TS 文本。确定性：节点类型字典序、根键保持单源声明序。"""
    projection = project_static_outputs()
    lines: list[str] = [
        "// AUTO-GENERATED by scripts/dev/gen_node_outputs_ts.py. DO NOT EDIT.",
        f"// 唯一事实源：src/atlas/graph/node_outputs.py；重新生成：{GENERATE_COMMAND}",
        "// 打包 AQ（docs/124，ADR T35）：构建期生成、提交入仓、后端守产物新鲜度。",
        "",
        "export const STATIC_OUTPUT_KEYS: Record<string, string[]> = {",
    ]
    for node_type in sorted(projection):
        roots = projection[node_type]["roots"]
        rendered = ", ".join(f"'{root}'" for root in roots)
        lines.append(f"  {node_type}: [{rendered}],")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
